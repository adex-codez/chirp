// Package apicodegen generates the mobile client's copy of the API's
// machine-readable error codes.
//
// The server's codes live in one place, `internal/response/codes.go`. This
// package reads that file and renders the matching TypeScript module, so a
// code added on the server reaches the client without anyone remembering to
// update a second list.
package apicodegen

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const (
	// CodesSource is the file that defines the codes, relative to the repo root.
	CodesSource = "server/internal/response/codes.go"

	// OutputPath is the generated TypeScript module, relative to the repo root.
	OutputPath = "chirp-mobile/src/lib/api-codes.ts"
)

// codePrefix marks the constants that hold error codes.
const codePrefix = "Code"

// ParseCodes reads the code constants out of a Go source file.
//
// Only exported string constants whose name starts with "Code" are returned,
// so the file can hold other constants without them leaking into the client.
func ParseCodes(path string) ([]string, error) {
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", path, err)
	}

	var codes []string
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.CONST {
			continue
		}
		for _, spec := range gen.Specs {
			value, ok := spec.(*ast.ValueSpec)
			if !ok || len(value.Names) != 1 || len(value.Values) != 1 {
				continue
			}
			name := value.Names[0].Name
			if !strings.HasPrefix(name, codePrefix) || !ast.IsExported(name) {
				continue
			}
			literal, ok := value.Values[0].(*ast.BasicLit)
			if !ok || literal.Kind != token.STRING {
				continue
			}
			code, err := strconv.Unquote(literal.Value)
			if err != nil {
				return nil, fmt.Errorf("read %s.%s: %w", path, name, err)
			}
			codes = append(codes, code)
		}
	}

	if len(codes) == 0 {
		return nil, fmt.Errorf("no error codes found in %s", path)
	}

	sort.Strings(codes)
	return codes, nil
}

// Render turns the codes into the TypeScript module the mobile app imports.
func Render(codes []string) string {
	var out strings.Builder
	out.WriteString("// Code generated by server/cmd/apicodes. DO NOT EDIT.\n")
	out.WriteString("//\n")
	out.WriteString("// The codes the Chirp API can return. `CODE_MESSAGES` in ./api-messages.ts\n")
	out.WriteString("// is typed against this list, so the compiler fails when a code is added\n")
	out.WriteString("// on the server without a message on the client.\n")
	out.WriteString("//\n")
	out.WriteString("// Run `task.ps1 generate` to refresh this file.\n\n")
	out.WriteString("export const API_CODES = [\n")
	for _, code := range codes {
		fmt.Fprintf(&out, "  '%s',\n", code)
	}
	out.WriteString("] as const;\n\n")
	out.WriteString("export type ApiCode = (typeof API_CODES)[number];\n\n")
	out.WriteString("/** Narrows an unknown string to a code the API can return. */\n")
	out.WriteString("export function isApiCode(value: string): value is ApiCode {\n")
	out.WriteString("  return (API_CODES as readonly string[]).includes(value);\n")
	out.WriteString("}\n")
	return out.String()
}

// Generate renders the client module for the codes defined in the server.
func Generate(root string) (string, error) {
	codes, err := ParseCodes(filepath.Join(root, CodesSource))
	if err != nil {
		return "", err
	}
	return Render(codes), nil
}

// FindRepoRoot walks up from start looking for the directory that holds both
// the server module and the mobile app.
func FindRepoRoot(start string) (string, error) {
	current, err := filepath.Abs(start)
	if err != nil {
		return "", err
	}
	for {
		if isRepoRoot(current) {
			return current, nil
		}
		parent := filepath.Dir(current)
		if parent == current {
			return "", fmt.Errorf("no repository root found above %s", start)
		}
		current = parent
	}
}

func isRepoRoot(dir string) bool {
	for _, marker := range []string{
		filepath.Join("server", "go.mod"),
		filepath.Join("chirp-mobile", "package.json"),
	} {
		if _, err := os.Stat(filepath.Join(dir, marker)); err != nil {
			return false
		}
	}
	return true
}
